export class Donations {
  readonly #rawClient: RawClient;
  readonly #servers: Servers;
  readonly #auth: AuthSchemes;

  constructor(rawClient: RawClient, servers: Servers, auth: AuthSchemes) {
    this.#rawClient = rawClient;
    this.#servers = servers;
    this.#auth = auth;
  }

  /**
   * Get a list of donation campaigns.
   *
   * @remarks
   * Queries the available donation campaigns for a donation based on the donation context (like
   * merchant account, currency, and locale). The response contains active donation campaigns.
   *
   * @returns OK - the request has succeeded.
   *
   * @throws {@link Donations.PostDonationCampaignsError} when the API answers with an error status
   * — narrow on `err.payload.kind`
   *
   * @throws {@link AdyenError} when no usable response was produced: a connection failure, a
   * timeout, a body that would not decode, a value that would not encode, or a credential that
   * could not be obtained
   */
  postDonationCampaigns(
    request: Donations.PostDonationCampaignsRequest,
    options?: RequestOptions,
  ): ApiPromise<DonationCampaignsResponse, Donations.PostDonationCampaignsError> {
    return this.#rawClient.execute(
      {
        method: "POST",
        urlTemplate: this.#servers.default("/donationCampaigns"),
        auth: anyAuth(this.#auth.basicAuth, this.#auth.apiKeyAuth),
        pathParams: [],
        query: [],
        headers: [{ name: "Idempotency-Key", value: request.idempotencyKey, schema: s.optional(s.string()) }],
        body: {
          kind: "json",
          value: request.body,
          schema: s.optional(s.lazy(() => donationCampaignsRequestSchema)),
        },
      },
      {
        success: { kind: "json", schema: donationCampaignsResponseSchema },
        errorFactory: Donations.PostDonationCampaignsError,
      },
      options,
    );
  }

  /**
   * Make a donation
   *
   * @remarks
   * Takes in the donation token generated by the `/payments` request and uses it to make the
   * donation.
   *
   * For more information, see [Donations](https://docs.adyen.com/online-payments/donations).
   *
   * @returns OK - the request has succeeded.
   *
   * @throws {@link Donations.PostDonationsError} when the API answers with an error status — narrow
   * on `err.payload.kind`
   *
   * @throws {@link AdyenError} when no usable response was produced: a connection failure, a
   * timeout, a body that would not decode, a value that would not encode, or a credential that
   * could not be obtained
   */
  postDonations(
    request: Donations.PostDonationsRequest,
    options?: RequestOptions,
  ): ApiPromise<DonationPaymentResponse, Donations.PostDonationsError> {
    return this.#rawClient.execute(
      {
        method: "POST",
        urlTemplate: this.#servers.default("/donations"),
        auth: anyAuth(this.#auth.basicAuth, this.#auth.apiKeyAuth),
        pathParams: [],
        query: [],
        headers: [{ name: "Idempotency-Key", value: request.idempotencyKey, schema: s.optional(s.string()) }],
        body: {
          kind: "json",
          value: request.body,
          schema: s.optional(s.lazy(() => donationPaymentRequestSchema)),
        },
      },
      {
        success: { kind: "json", schema: donationPaymentResponseSchema },
        errorFactory: Donations.PostDonationsError,
      },
      options,
    );
  }
}

