import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";
import { amount110Schema, type Amount110 } from "./amount110.js";
import { counterparty11Schema, type Counterparty11 } from "./counterparty11.js";

/**
 * The details of the payment. You must show your user these details before they confirm or cancel
 * the payment.
 */
export type PaymentDetails11 = {
  /** The amount of the payment. */
  amount: Amount110;
  /** Contains information about the party that receives the payment funds. */
  counterparty: Counterparty11;
  /**
   * The description for the payment. It is generated by the payment method, such as iDEAL, and
   * should be shown to the user.
   */
  description: string;
  /**
   * The expiration date of the payment in ISO DateTime format, as described on ISO 20022
   * (YYYY-MM-DDThh:mm:ss.sss+/-hh:mm).
   *
   * Example: **2025-12-30T14:15:30+01:00**
   */
  expiresAt: Date;
};

export const paymentDetails11Schema: Schema<PaymentDetails11> = s.object<PaymentDetails11>({
  amount: amount110Schema,
  counterparty: counterparty11Schema,
  description: s.string(),
  expiresAt: s.dateTime(),
});
