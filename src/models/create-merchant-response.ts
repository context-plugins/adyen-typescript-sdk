import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";

export type CreateMerchantResponse = {
  /**
   * The unique identifier of the [business
   * line](https://docs.adyen.com/api-explorer/#/legalentity/latest/post/businessLines).
   */
  businessLineId?: string;
  /** The unique identifier of the company account. */
  companyId?: string;
  /** Your description for the merchant account, maximum 300 characters. */
  description?: string;
  /**
   * The unique identifier of the merchant account. If Adyen set up a template for the `reference`,
   * then the `id` will have the same value as the `reference` that you sent in the request.
   * Otherwise, the value is generated by Adyen.
   */
  id?: string;
  /**
   * The unique identifier of the [legal
   * entity](https://docs.adyen.com/api-explorer/#/legalentity/latest/post/legalEntities).
   */
  legalEntityId?: string;
  /**
   * Partner pricing plan for the merchant, applicable for merchants under AfP managed company
   * accounts.
   */
  pricingPlan?: string;
  /** Your reference for the merchant account. */
  reference?: string;
};

export const createMerchantResponseSchema: Schema<CreateMerchantResponse> = s.object<CreateMerchantResponse>({
  businessLineId: s.optional(s.string()),
  companyId: s.optional(s.string()),
  description: s.optional(s.string()),
  id: s.optional(s.string()),
  legalEntityId: s.optional(s.string()),
  pricingPlan: s.optional(s.string()),
  reference: s.optional(s.string()),
});
