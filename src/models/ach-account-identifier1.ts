import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";

/**
 * Identifiers relevant for Automated Clearing House (ACH) payments, primarily used in the United
 * States.
 */
export type AchAccountIdentifier1 = {
  /**
   * The last digits of the account number. If the accountNumber is tokenized, this field contains
   * the last digits of the non-tokenized account number. This helps users verify the account
   * without seeing the full number.
   */
  accountLastDigits?: string;
  /** The account number of the bank account. */
  accountNumber: string;
  /**
   * Indicates whether the account number is tokenized. A tokenized account number is a unique ID
   * generated by a bank to protect the user's actual account number.
   */
  isTokenized?: boolean;
  /**
   * The [routing number](https://en.wikipedia.org/wiki/ABA_routing_transit_number), without
   * separators or whitespace.
   */
  routingNumber: string;
};

export const achAccountIdentifier1Schema: Schema<AchAccountIdentifier1> = s.object<AchAccountIdentifier1>({
  accountLastDigits: s.optional(s.string()),
  accountNumber: s.string(),
  isTokenized: s.optional(s.boolean()),
  routingNumber: s.string(),
});
